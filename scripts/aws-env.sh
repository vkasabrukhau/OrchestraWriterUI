#!/usr/bin/env bash
# Writes .env.aws: the settings that point a local `npm run dev:aws` at the
# shared AWS stack (Aurora, the S3 bucket, the transcription state machine).
#
# Nothing secret is committed: every value is read from AWS with your own
# credentials (`aws configure`), and .env.aws is gitignored. This repo is
# public, so keep it that way: never paste these values into a tracked file.
#
# Needs: the collaborator policy in infra/README.md (rds-db:connect + bucket),
# plus rds:DescribeDBClusters. Google sign-in values are copied from SSM only
# if you may read /orchestra-writer/* (ssm:GetParameter + kms:Decrypt);
# without them the Google button is simply hidden.
#
#   scripts/aws-env.sh          # writes .env.aws
#   npm run db:ping:aws         # checks the database connection
#   npm run dev:aws             # the app on http://localhost:3000, against AWS
set -euo pipefail
cd "$(dirname "$0")/.."

REGION="${AWS_REGION:-us-east-1}"
APP="${APP_NAME:-orchestra-writer}"
CLUSTER="${DB_CLUSTER:-orchestra-db-1}"
BUCKET="${S3_AUDIO_BUCKET:-orchestra-writer-s3}"
OUT="${OUT:-.env.aws}"

if ! who=$(aws sts get-caller-identity --query Arn --output text 2>/dev/null); then
  echo "No AWS credentials. Run 'aws configure' (or set AWS_PROFILE) first." >&2
  exit 1
fi
echo "AWS identity: $who"

host=$(aws rds describe-db-clusters --region "$REGION" --db-cluster-identifier "$CLUSTER" \
  --query 'DBClusters[0].Endpoint' --output text)
state_machine=$(aws stepfunctions list-state-machines --region "$REGION" \
  --query "stateMachines[?name=='$APP-transcription'].stateMachineArn | [0]" --output text 2>/dev/null || true)
[ "$state_machine" = "None" ] && state_machine=""

ssm() {
  aws ssm get-parameter --region "$REGION" --name "/$APP/$1" --with-decryption \
    --query Parameter.Value --output text 2>/dev/null || true
}
google_id=$(ssm GOOGLE_CLIENT_ID)
google_secret=$(ssm GOOGLE_CLIENT_SECRET)

umask 077
cat > "$OUT" <<EOF
# Generated by scripts/aws-env.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Gitignored; do not commit.
# Local dev against the shared AWS stack. AWS credentials come from ~/.aws.

AWS_REGION=$REGION

# Aurora PostgreSQL, IAM auth: no password, a token is made per connection.
DB_HOST=$host
DB_PORT=5432
DB_NAME=postgres
DB_USER=postgres
DB_PASSWORD=
DB_SSL=true
DB_SSL_VERIFY=true

# Real S3: both endpoints empty (they would otherwise default to S3Mock).
S3_AUDIO_BUCKET=$BUCKET
S3_ENDPOINT=
S3_PUBLIC_ENDPOINT=

# Local sessions are signed with a local secret, not the production one.
BETTER_AUTH_SECRET=local-only-secret-not-for-production
BETTER_AUTH_URL=http://localhost:3000
GOOGLE_CLIENT_ID=$google_id
GOOGLE_CLIENT_SECRET=$google_secret

# Leave the pipeline inline locally; set PIPELINE_MODE=stepfunctions to use AWS.
STATE_MACHINE_ARN=$state_machine
PIPELINE_MODE=inline
EOF

echo "Wrote $OUT (database $host, bucket $BUCKET${google_id:+, Google sign-in})."
echo "Next: npm run db:ping:aws, then npm run dev:aws"
